#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const pluginDir = resolve(process.argv[2] ?? ".");
const templatesDir = join(pluginDir, "templates");
const outFile = join(pluginDir, "src", "template-content.ts");

const files = [
	["form-notification.html", "formNotificationHtml"],
	["form-notification.txt", "formNotificationText"],
	["login-notification.html", "loginNotificationHtml"],
	["login-notification.txt", "loginNotificationText"],
];

const exports = [];

for (const [filename, exportName] of files) {
	const path = join(templatesDir, filename);
	try {
		const content = readFileSync(path, "utf8");
		exports.push(`export const ${exportName} = ${JSON.stringify(content)};`);
	} catch {
		// Plugin may not include every template file.
	}
}

if (exports.length === 0) {
	console.error(`No templates found in ${templatesDir}`);
	process.exit(1);
}

writeFileSync(
	outFile,
	`// Auto-generated by scripts/embed-templates.mjs — do not edit by hand.\n\n${exports.join("\n\n")}\n`,
);
console.log(`Wrote ${outFile} (${exports.length} template(s))`);
